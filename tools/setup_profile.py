"""Applies Glass Arc to a Zen profile (Zen must be closed), or removes it.

usage: setup_profile.py install|uninstall PROFILE_DIR REPO_DIR linux|windows

install.sh calls this; install.ps1 does the same steps in PowerShell.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import time
from pathlib import Path

MOD_ID = "local-glass-arc"
MARK_START = "/* >>> Glass Arc >>> */"
MARK_END = "/* <<< Glass Arc <<< */"
PREF_RE = re.compile(r'^user_pref\("([^"]+)",\s*(.*)\);\s*$')


def backup(profile: Path) -> Path:
    stamp = time.strftime("%Y-%m-%d_%H-%M-%S")
    dest = profile / "glass-arc-backup" / stamp
    n = 1
    while dest.exists():
        n += 1
        dest = profile / "glass-arc-backup" / f"{stamp}_{n}"
    dest.mkdir(parents=True)
    for rel in ("prefs.js", "zen-themes.json", "chrome/userChrome.css", "chrome/zen-themes.css"):
        src = profile / rel
        if src.exists():
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest / rel)
    return dest


def read_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def rebuild_mods_css(profile: Path) -> None:
    """Writes chrome/zen-themes.css the way Zen Mods does, with every enabled mod."""
    mods = read_json(profile / "zen-themes.json", {})
    parts = [
        "/* Zen Mods - Generated by ZenMods.\n",
        f"* FILE GENERATED AT: {time.strftime('%A, %B %d, %Y at %I:%M:%S %p')}\n",
        "* DO NOT EDIT THIS FILE DIRECTLY!\n* Your changes will be overwritten.\n"
        "* Instead, go to the preferences and edit the mods there.\n*/\n",
    ]
    for mod in mods.values():
        if mod.get("enabled") is False:
            continue
        css = profile / "chrome" / "zen-themes" / mod["id"] / "chrome.css"
        if not css.exists():
            continue
        parts.append(f"\n/* Name: {mod.get('name')} */\n")
        parts.append(f"/* Description: {mod.get('description')} */\n")
        parts.append(f"/* Author: @{mod.get('author')} */\n")
        parts.append(css.read_text(encoding="utf-8"))
    parts.append("\n/* End of Zen Mods */\n")
    (profile / "chrome" / "zen-themes.css").write_text("".join(parts), encoding="utf-8")


def set_block(path: Path, block: str | None) -> None:
    """Puts our block into a user CSS file (or takes it out), keeping the rest."""
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    text = re.sub(re.escape(MARK_START) + r".*?" + re.escape(MARK_END) + r"\n?", "", text, flags=re.S)
    if block:
        text = text.rstrip("\n") + ("\n\n" if text.strip() else "") + f"{MARK_START}\n{block.rstrip()}\n{MARK_END}\n"
    if text.strip() or path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def write_prefs(profile: Path, forced: list[str], defaults: list[str]) -> None:
    """forced lines replace existing values; defaults only fill in missing ones."""
    path = profile / "prefs.js"
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    existing = {m.group(1) for line in lines if (m := PREF_RE.match(line))}
    forced_keys = {PREF_RE.match(line).group(1) for line in forced}
    kept = [line for line in lines if not ((m := PREF_RE.match(line)) and m.group(1) in forced_keys)]
    added = forced + [line for line in defaults if PREF_RE.match(line).group(1) not in existing]
    path.write_text("\n".join(kept + added) + "\n", encoding="utf-8")


def pref_lines(path: Path) -> list[str]:
    return [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if PREF_RE.match(line.strip())]


def mod_default_prefs(prefs_json: Path) -> list[str]:
    out = []
    for p in json.loads(prefs_json.read_text(encoding="utf-8")):
        value = p["defaultValue"]
        value = ("true" if value else "false") if isinstance(value, bool) else json.dumps(str(value), ensure_ascii=False)
        out.append(f'user_pref("{p["property"]}", {value});')
    return out


def downloads_instead_of_library(profile: Path) -> bool:
    """Downloads takes Library's place at the bottom of the sidebar."""
    path = profile / "prefs.js"
    text = path.read_text(encoding="utf-8")
    m = re.search(r'^user_pref\("browser\.uiCustomization\.state", (".*")\);$', text, re.M)
    if not m:
        return False
    state = json.loads(json.loads(m.group(1)))
    placements = state.setdefault("placements", {})
    for area in placements.values():
        for widget in ("zen-library-button", "downloads-button"):
            while widget in area:
                area.remove(widget)
    placements.setdefault("zen-sidebar-foot-buttons", []).append("downloads-button")
    placements.setdefault("widget-overflow-fixed-list", []).append("zen-library-button")
    dirty = state.setdefault("dirtyAreaCache", [])
    for area in ("zen-sidebar-foot-buttons", "widget-overflow-fixed-list"):
        if area not in dirty:
            dirty.append(area)
    line = 'user_pref("browser.uiCustomization.state", ' + json.dumps(json.dumps(state, separators=(",", ":"))) + ");"
    path.write_text(text[:m.start()] + line + text[m.end():], encoding="utf-8")
    return True


def install(profile: Path, repo: Path, platform: str) -> None:
    saved = backup(profile)
    chrome = profile / "chrome"

    mod_dir = chrome / "zen-themes" / MOD_ID
    shutil.copytree(repo / "mod" / MOD_ID, mod_dir, dirs_exist_ok=True)

    mods = read_json(profile / "zen-themes.json", {})
    mods[MOD_ID] = {
        "id": MOD_ID,
        "name": "Glass Arc",
        "description": "Frosted glass sidebar with gradient tint, Nova-style buttons, glass AI panel",
        "homepage": "",
        "style": f"https://localhost.invalid/{MOD_ID}/chrome.css",
        "readme": f"https://localhost.invalid/{MOD_ID}/readme.md",
        "preferences": f"https://localhost.invalid/{MOD_ID}/preferences.json",
        "image": "",
        "author": "local",
        "version": "1.1.0",
        "tags": ["glass", "arc", "local"],
        "createdAt": mods.get(MOD_ID, {}).get("createdAt", time.strftime("%Y-%m-%d")),
        "updatedAt": time.strftime("%Y-%m-%d"),
        "enabled": True,
    }
    (profile / "zen-themes.json").write_text(json.dumps(mods, indent=2, ensure_ascii=False), encoding="utf-8")
    rebuild_mods_css(profile)

    set_block(chrome / "userChrome.css", (repo / "profile" / "userChrome.css").read_text(encoding="utf-8"))

    js_dir = chrome / "JS"
    js_dir.mkdir(parents=True, exist_ok=True)
    for script in (repo / "profile" / "JS").glob("*.uc.js"):
        shutil.copy2(script, js_dir / script.name)

    write_prefs(
        profile,
        forced=pref_lines(repo / "prefs" / "common.prefs") + pref_lines(repo / "prefs" / f"{platform}.prefs"),
        defaults=mod_default_prefs(repo / "mod" / MOD_ID / "preferences.json"),
    )
    # on a profile Zen has never opened, glassarc-style.uc.js does it instead
    if downloads_instead_of_library(profile):
        write_prefs(profile, forced=['user_pref("mod.glassarc.downloads-moved", true);'], defaults=[])
    print(f"   резервная копия: {saved}")


def uninstall(profile: Path) -> None:
    saved = backup(profile)
    chrome = profile / "chrome"
    shutil.rmtree(chrome / "zen-themes" / MOD_ID, ignore_errors=True)
    mods = read_json(profile / "zen-themes.json", {})
    if mods.pop(MOD_ID, None) is not None:
        (profile / "zen-themes.json").write_text(json.dumps(mods, indent=2, ensure_ascii=False), encoding="utf-8")
        rebuild_mods_css(profile)
    set_block(chrome / "userChrome.css", None)
    (chrome / "JS" / "glassarc-style.uc.js").unlink(missing_ok=True)
    print(f"   резервная копия: {saved}")


if __name__ == "__main__":
    action, profile_dir = sys.argv[1], Path(sys.argv[2])
    if action == "install":
        install(profile_dir, Path(sys.argv[3]), sys.argv[4])
    else:
        uninstall(profile_dir)
